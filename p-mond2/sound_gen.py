# Erzeugt sound.json für das Mond-Video aus timing.json
import json
T = json.load(open('p-mond2/timing.json')); S = T['sentences']; P = T['phrases']
at = lambda i, f: round(S[i][0] + (S[i][1] - S[i][0]) * f, 3)
ph = lambda w: next(x[0] for x in P if w in x[2])
ev = []; A = lambda **k: ev.append(k)
POP = at(0, .75)
A(t=0.0, type='shimmer', dd=1.2, gain=.35); A(t=.35, type='boom', dd=1.0, f=50, gain=.35)
A(t=POP, type='boom', dd=1.8, f=34, gain=.6); A(t=POP, type='glitch', dd=.4, gain=.18); A(t=POP + .05, type='scratch', dd=.4, gain=.2)
for x in range(10): A(t=round(POP + .1 + x * .1, 3), type='pop', f=500 + x * 80, gain=.08, pan=x / 10)
kinds = [dict(type='whoosh', dd=.55, f0=400, f1=4500), dict(type='reverse', dd=.6), dict(type='swipe', dd=.3), dict(type='riser', dd=.5, f0=300, f1=1500), dict(type='whoosh', dd=.8, f0=150, f1=1800), dict(type='swipe', dd=.22), dict(type='reverse', dd=.45), dict(type='wind', dd=.7)]
for i, (a, b) in enumerate(S[1:]):
    k = dict(kinds[i % len(kinds)]); k.update(t=a, pre=.8 if k['type'] != 'wind' else .4, gain=.1, pan=.3 + .4 * (i % 2)); A(**k)
no = ph('Ist es aber'); A(t=no, type='boom', dd=.8, f=55, gain=.4); A(t=no, type='glitch', dd=.25, gain=.15)
lp = ph('Und am Ende'); A(t=lp, type='reverse', dd=1.4, gain=.14); A(t=lp + 1.6, type='shimmer', dd=1.0, gain=.35)
A(t=at(2, .35), type='wind', dd=2.0, gain=.14)
ref = ph('Er spiegelt'); A(t=ref, type='riser', dd=.9, f0=500, f1=2000, gain=.1); A(t=ref + .9, type='swipe', dd=.4, gain=.14)
A(t=at(4, .3), type='whoosh', dd=1.4, f0=1500, f1=200, gain=.15); A(t=at(4, .6), type='wind', dd=1.6, gain=.15)
A(t=at(5, .2), type='riser', dd=1.6, f0=150, f1=900, gain=.12)
sh = ph('Die Gezeiten'); A(t=sh, type='reverse', dd=1.2, gain=.15)
for x in range(6): A(t=round(sh + x * .2, 3), type='tick', f=2200 - x * 150, gain=.11)
cal = ph('Viele Korallen'); A(t=cal, type='shimmer', dd=2.0, gain=.35)
for x in range(5): A(t=round(cal + .3 + x * .15, 3), type='pop', f=700 + x * 90, gain=.15)
for x in range(8): A(t=round(S[8][0] + .1 + x * (.3 + x * .05), 3), type='tick', f=1500, gain=.14 - x * .012)
ax = ph('Dafür müssen'); A(t=S[9][0], type='riser', dd=ax - S[9][0], f0=200, f1=3200, gain=.15); A(t=ax, type='boom', dd=1.0, f=46, gain=.38)
js = ph('Und genau')
for x in range(4): A(t=round(js + .2 + x * .25, 3), type='pop', f=600 + x * 120, gain=.15)
A(t=S[11][0], type='wind', dd=2.5, gain=.1); A(t=ph('so wie'), type='swipe', dd=.4, gain=.15)
ex = ph('Mit extremen'); A(t=S[12][0], type='boom', dd=1.0, f=44, gain=.4); A(t=ex, type='wind', dd=2.0, gain=.18)
A(t=S[13][0], type='boom', dd=1.2, f=42, gain=.45); A(t=ph('Der Mond entfernt') - .2, type='shimmer', dd=1.2, gain=.45)
for x in range(12): A(t=round(S[14][0] + .1 + x * .12, 3), type='tick', f=2600, gain=.1)
A(t=ph('Das haben'), type='riser', dd=.7, f0=1000, f1=3500, gain=.12)
A(t=S[15][1] + .2, type='boom', dd=1.6, f=42, gain=.4); A(t=S[15][1] + .25, type='shimmer', dd=1.6, gain=.6)
json.dump({"dur": T['dur'], "bpm": 96, "seed": 21, "chords": [[50, 57, 62, 65], [53, 57, 60, 65], [46, 53, 58, 62], [48, 55, 60, 64], [45, 52, 57, 60], [53, 60, 65, 69]], "pattern": [0, 1, 2, 3], "pulse_from": 2.0, "pulse_to": round(S[-1][1], 2), "events": ev}, open('p-mond2/sound.json', 'w'))
print(len(ev), 'Effekte')
